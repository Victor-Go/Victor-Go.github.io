export type Lang = "zh" | "en";

/** The first language the browser prefers decides; anything that is not Chinese gets English. Never persisted. */
export function detectLang(languages: readonly string[] | undefined): Lang {
  const first = languages?.find((l) => l.trim() !== "")?.toLowerCase() ?? "";
  return first.startsWith("zh") ? "zh" : "en";
}

export const getDefaultLang = (): Lang => detectLang(typeof navigator === "undefined" ? undefined : navigator.languages);

