export type Lang = "zh" | "en";

/** Picks the initial UI language from the browser. Never persisted. */
export function detectLang(nav: Pick<Navigator, "language"> = navigator): Lang {
  return /^zh\b/i.test(nav.language ?? "") ? "zh" : "en";
}

